//! Group E's `/openapi/v3` endpoint (`docs/APISERVER.md`'s own "not yet
//! landed" list): embeds every vendored OpenAPI v3 spec file verbatim into
//! the binary, keyed by the real HTTP path it's served at.
//!
//! The filenames under `vendor/openapi-spec/v3/` are not this crate's own
//! naming convention — they're vendored *as-is* from upstream's own
//! `api/openapi-spec/v3/` tree (`vendor/refresh.sh`), which
//! `hack/update-openapi-spec.sh` generates to mirror exactly what a real
//! running apiserver serves at `/openapi/v3/...`. Upstream's own encoding
//! is mechanical and confirmed directly from the vendored filenames
//! themselves (not guessed): `/`-separated HTTP path segments joined with
//! `__`, suffixed `_openapi.json` — e.g.
//! `apis__admissionregistration.k8s.io__v1_openapi.json` serves
//! `/openapi/v3/apis/admissionregistration.k8s.io/v1`. Reversing that
//! encoding is the entire parsing job here; the file *content* is served
//! completely unmodified — this crate has no OpenAPI v3 generator of its
//! own to diverge from what upstream actually publishes for this exact
//! vendored ref.

use std::path::Path;

pub struct ServedDoc {
    pub http_path: String,
    pub abs_file_path: String,
    pub hash_hex: String,
}

pub fn parse_all(openapi_dir: &Path) -> Vec<ServedDoc> {
    let mut docs = Vec::new();
    for entry in std::fs::read_dir(openapi_dir).unwrap_or_else(|e| panic!("reading {}: {e}", openapi_dir.display())) {
        let entry = entry.expect("reading a dir entry");
        let path = entry.path();
        let Some(file_name) = path.file_name().and_then(|n| n.to_str()) else { continue };
        let Some(stripped) = file_name.strip_suffix("_openapi.json") else { continue };
        let http_path = stripped.replace("__", "/");
        let content = std::fs::read(&path).unwrap_or_else(|e| panic!("reading {}: {e}", path.display()));
        let hash_hex = fnv1a_hex(&content);
        docs.push(ServedDoc { http_path, abs_file_path: path.to_string_lossy().into_owned(), hash_hex });
    }
    docs.sort_by(|a, b| a.http_path.cmp(&b.http_path));
    docs
}

/// A stable content hash for the client-caching `?hash=` query parameter
/// real `/openapi/v3` responses carry — this crate's own hash of its own
/// served bytes, not a reproduction of whatever hash algorithm upstream's
/// real apiserver happens to use internally (nothing in the discovery
/// protocol requires the two to match: a client only ever compares this
/// server's hash against a value this same server previously returned).
/// FNV-1a: simple, dependency-free, and every build.rs concern in this
/// crate is already hand-rolled parsing rather than pulling in a crate for
/// a one-off need.
fn fnv1a_hex(data: &[u8]) -> String {
    let mut hash: u64 = 0xcbf29ce484222325;
    for &b in data {
        hash ^= b as u64;
        hash = hash.wrapping_mul(0x100000001b3);
    }
    format!("{hash:016x}")
}

pub fn render(docs: &[ServedDoc]) -> String {
    let mut out = String::new();
    out.push_str("/// One vendored OpenAPI v3 document, embedded verbatim.\n");
    out.push_str("#[derive(Debug, Clone, Copy)]\n");
    out.push_str("pub struct ServedOpenApiDoc {\n");
    out.push_str("    /// The HTTP path this is served at, relative to `/openapi/v3/`\n");
    out.push_str("    /// (e.g. `\"apis/apps/v1\"`).\n");
    out.push_str("    pub path: &'static str,\n");
    out.push_str("    pub hash: &'static str,\n");
    out.push_str("    pub content: &'static [u8],\n");
    out.push_str("}\n\n");
    out.push_str("/// Auto-generated by `build/openapi_serve.rs` from every\n");
    out.push_str("/// `vendor/openapi-spec/v3/*.json` file, sorted by `path`.\n");
    out.push_str("pub static OPENAPI_V3_DOCS: &[ServedOpenApiDoc] = &[\n");
    for d in docs {
        out.push_str(&format!(
            "    ServedOpenApiDoc {{ path: {:?}, hash: {:?}, content: include_bytes!({:?}) }},\n",
            d.http_path, d.hash_hex, d.abs_file_path
        ));
    }
    out.push_str("];\n");
    out
}
